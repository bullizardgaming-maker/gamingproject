/** Plural keys are written key_one / key_other …; callers pass the base key with a count. */
export type PluralBase = { [K in MessageKey]: K extends `${infer B}_other` ? B : never }[MessageKey];
/** A translation: any subset of the keys, plus the extra plural forms a language needs (Arabic has six). */
